function applyStaticLanguage() {
  const language = getAppLanguage();
  document.documentElement.lang = language;

  TEXT_BINDINGS.forEach(([selector, key]) =>
    setText(selector, key)
  );

  DIRECT_TEXT_BINDINGS.forEach(([selector, key]) =>
    setDirectText(selector, key)
  );

  PLACEHOLDER_BINDINGS.forEach(([selector, key]) =>
    setPlaceholder(selector, key)
  );

  CONTROL_LABEL_BINDINGS.forEach(([selector, key]) =>
    setControlLabel(selector, key)
  );

  setControlLabel("#dateFromFilter", "filter.from");
  setControlLabel("#dateToFilter", "filter.to");

  setPopularSearch(
    "[data-landing-query]:nth-of-type(1)",
    "landing.popular.marathon"
  );
  setPopularSearch(
    "[data-landing-query]:nth-of-type(2)",
    "landing.popular.triathlon"
  );
  setPopularSearch(
    "[data-landing-query]:nth-of-type(3)",
    "landing.popular.ultra"
  );
  setPopularSearch(
    "[data-landing-query]:nth-of-type(4)",
    "landing.popular.trail"
  );
  setPopularSearch(
    "[data-landing-query]:nth-of-type(5)",
    "landing.popular.half"
  );

  [
    ["#mapToolsToggle", "map.tools"],
    ["#locateBtn", "map.location"],
    ["#favoritesBtn", "map.favorites"],
    ["#mapStyleBtn", "map.style"]
  ].forEach(([selector, key]) => {
    setAttribute(selector, "title", key);
    setAttribute(selector, "aria-label", key);
  });

  document
    .querySelectorAll(".app-language-select, #profileLanguageSelect")
    .forEach(select => {
      select.value = language;
      select.setAttribute(
        "aria-label",
        translate("language.label")
      );
    });
}

function setAppLanguage(language) {
  const normalizedLanguage =
    language === "de"
      ? "de"
      : "en";

  localStorage.setItem(
    LANGUAGE_STORAGE_KEY,
    normalizedLanguage
  );

  applyStaticLanguage();

  if (typeof applyFilters === "function") {
    applyFilters();
  }

  const seasonPlanner =
    document.getElementById(
      "seasonPlannerModal"
    );

  if (
    seasonPlanner?.classList.contains("open") &&
    typeof renderSeasonPlanner === "function"
  ) {
    renderSeasonPlanner();
    applyStaticLanguage();
  }

  document.dispatchEvent(
    new CustomEvent(
      "app-language-changed",
      {
        detail: {
          language: normalizedLanguage
        }
      }
    )
  );
}

function initializeLanguageControls() {
  document
    .querySelectorAll(
      ".app-language-select"
    )
    .forEach(select => {
      if (select.dataset.languageBound) {
        return;
      }

      select.dataset.languageBound = "true";

      select.addEventListener(
        "change",
        () => setAppLanguage(
          select.value
        )
      );
    });

  applyStaticLanguage();
}

