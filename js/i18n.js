function getAppLanguage() {
  return localStorage.getItem(LANGUAGE_STORAGE_KEY) === "de"
    ? "de"
    : "en";
}

function translate(key, fallback = "") {
  const language = getAppLanguage();
  return I18N[language]?.[key] || I18N.en[key] || fallback || key;
}

function translateTemplate(key, values = {}, fallback = "") {
  return Object.entries(values)
    .reduce(
      (text, [name, value]) =>
        text.replaceAll(
          `{${name}}`,
          String(value)
        ),
      translate(key, fallback)
    );
}

function setText(selector, key) {
  document.querySelectorAll(selector).forEach(element => {
    element.textContent = translate(key, element.textContent);
  });
}

function setPlaceholder(selector, key) {
  document.querySelectorAll(selector).forEach(element => {
    element.placeholder = translate(key, element.placeholder);
  });
}

function setAttribute(selector, attribute, key) {
  document.querySelectorAll(selector).forEach(element => {
    element.setAttribute(
      attribute,
      translate(key, element.getAttribute(attribute) || "")
    );
  });
}

function setDirectText(selector, key) {
  document.querySelectorAll(selector).forEach(element => {
    const textNode =
      [...element.childNodes]
        .find(node =>
          node.nodeType === Node.TEXT_NODE &&
          node.textContent.trim()
        );

    if (textNode) {
      textNode.textContent = `${translate(key)} `;
    }
  });
}

function setControlLabel(controlSelector, key) {
  document.querySelectorAll(controlSelector).forEach(control => {
    const label = control.closest("label");

    if (!label) {
      return;
    }

    const textNode =
      [...label.childNodes]
        .find(node =>
          node.nodeType === Node.TEXT_NODE &&
          node.textContent.trim()
        );

    if (textNode) {
      textNode.textContent = `${translate(key)} `;
    }
  });
}

function setPopularSearch(selector, key) {
  document.querySelectorAll(selector).forEach(button => {
    const value = translate(key);
    button.textContent = value;
    button.dataset.landingQuery = value;
  });
}

