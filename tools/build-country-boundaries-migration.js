const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SOURCE = path.join(ROOT, "data", "reference", "natural-earth-50m-admin-0-countries.geojson");
const OUTPUT = path.join(ROOT, "supabase", "migrations", "20260802_postgis_country_boundaries.sql");
const ALIASES = {
  DEU: ["germany", "deutschland"], AUT: ["austria", "österreich"], CHE: ["switzerland", "schweiz"],
  ESP: ["spain"], NLD: ["netherlands"], ITA: ["italy"], SWE: ["sweden"], DNK: ["denmark"],
  NOR: ["norway"], PRT: ["portugal"], FRA: ["france"], LUX: ["luxembourg"], MLT: ["malta"],
  GBR: ["united kingdom", "uk", "great britain"], FIN: ["finland"], ISL: ["iceland"],
  ROU: ["romania"], HUN: ["hungary"], BEL: ["belgium"], IRL: ["ireland"], GRC: ["greece"],
  CZE: ["czech republic", "czechia"]
};

function sql(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function main() {
  const collection = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
  const features = new Map();
  for (const feature of collection.features || []) {
    const code = feature.properties?.ADM0_A3 || feature.properties?.ISO_A3;
    if (ALIASES[code]) features.set(code, feature.geometry);
  }
  const missing = Object.keys(ALIASES).filter(code => !features.has(code));
  if (missing.length) throw new Error(`Natural Earth countries missing: ${missing.join(", ")}`);

  const values = [...features].map(([code, geometry]) =>
    `  (${sql(code)}, array[${ALIASES[code].map(sql).join(", ")}], ` +
    `extensions.ST_Multi(extensions.ST_SetSRID(extensions.ST_GeomFromGeoJSON(${sql(JSON.stringify(geometry))}), 4326)), ` +
    `'Natural Earth 1:50m Admin 0 v5.1.1')`
  ).join(",\n");

  const migration = `-- Generated by tools/build-country-boundaries-migration.js from Natural Earth public-domain data.\n` +
`begin;\n\n` +
`create extension if not exists postgis with schema extensions;\n\n` +
`create table if not exists private.country_boundaries (\n` +
`  iso_a3 text primary key,\n  country_aliases text[] not null,\n` +
`  geom extensions.geometry(MultiPolygon, 4326) not null,\n` +
`  source_label text not null,\n  updated_at timestamptz not null default now()\n);\n\n` +
`insert into private.country_boundaries (iso_a3, country_aliases, geom, source_label) values\n${values}\n` +
`on conflict (iso_a3) do update set country_aliases = excluded.country_aliases, geom = excluded.geom, source_label = excluded.source_label, updated_at = now();\n\n` +
`create index if not exists country_boundaries_geom_gix on private.country_boundaries using gist (geom);\n` +
`revoke all on private.country_boundaries from public, anon, authenticated;\n\n` +
`create or replace function private.coordinates_within_country(p_country text, p_latitude double precision, p_longitude double precision)\n` +
`returns boolean language sql stable security invoker set search_path = pg_catalog, extensions, private as $$\n` +
`  select coalesce(bool_or(\n` +
`    extensions.ST_Covers(b.geom, extensions.ST_SetSRID(extensions.ST_Point(p_longitude, p_latitude), 4326))\n` +
`    or extensions.ST_DWithin(b.geom::extensions.geography, extensions.ST_SetSRID(extensions.ST_Point(p_longitude, p_latitude), 4326)::extensions.geography, 3000)\n` +
`  ), true) from private.country_boundaries b where lower(p_country) = any(b.country_aliases);\n$$;\n\n` +
`create or replace function private.run_country_polygon_validation() returns integer\n` +
`language plpgsql security definer set search_path = pg_catalog, public, private, extensions as $$\n` +
`declare issue_count integer; begin\n` +
`  insert into public.validation_issues (event_id, severity, rule_code, description, status)\n` +
`  select e.id, 'error', 'coordinates_outside_country_polygon', 'Coordinates are outside the declared country polygon.', 'open'\n` +
`  from public.events e where e.latitude is not null and e.longitude is not null\n` +
`    and not private.coordinates_within_country(e.country, private.try_parse_coordinate(e.latitude), private.try_parse_coordinate(e.longitude))\n` +
`  on conflict (entity_scope, rule_code) do update set severity = excluded.severity, description = excluded.description, status = 'open', resolved_at = null, resolved_by = null, updated_at = now();\n` +
`  get diagnostics issue_count = row_count;\n` +
`  update public.validation_issues vi set status = 'resolved', resolved_at = now(), updated_at = now()\n` +
`  where vi.status = 'open' and vi.rule_code = 'coordinates_outside_country_polygon' and not exists (\n` +
`    select 1 from public.events e where e.id = vi.event_id and e.latitude is not null and e.longitude is not null\n` +
`      and not private.coordinates_within_country(e.country, private.try_parse_coordinate(e.latitude), private.try_parse_coordinate(e.longitude))\n` +
`  );\n` +
`  insert into public.data_workflow_alerts (alert_scope, alert_code, severity, title, description, metadata)\n` +
`  select 'country:' || lower(e.country), 'country_polygon_missing', 'warning', 'Country polygon missing', 'No PostGIS country polygon is configured for ' || e.country, jsonb_build_object('country', e.country)\n` +
`  from public.events e where not exists (select 1 from private.country_boundaries b where lower(e.country) = any(b.country_aliases))\n` +
`  group by e.country on conflict (alert_scope, alert_code) do update set alert_status = 'open', last_detected_at = now(), occurrence_count = public.data_workflow_alerts.occurrence_count + 1, metadata = excluded.metadata, updated_at = now();\n` +
`  return issue_count; end; $$;\n\n` +
`revoke all on function private.coordinates_within_country(text, double precision, double precision) from public, anon, authenticated;\n` +
`revoke all on function private.run_country_polygon_validation() from public, anon, authenticated;\n\n` +
`do $schedule$ begin\n` +
`  if exists (select 1 from cron.job where jobname = 'sem-country-polygon-validation-hourly') then perform cron.unschedule('sem-country-polygon-validation-hourly'); end if;\n` +
`  perform cron.schedule('sem-country-polygon-validation-hourly', '23 * * * *', $cron$select private.run_country_polygon_validation();$cron$);\n` +
`end $schedule$;\n\n` +
`comment on table private.country_boundaries is 'Natural Earth country polygons used for precise coordinate validation; operational tables remain admin-only.';\n\ncommit;\n`;

  fs.writeFileSync(OUTPUT, migration, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)} with ${features.size} country polygons.`);
}

if (require.main === module) main();
